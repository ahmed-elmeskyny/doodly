import { writeFileSync, mkdirSync } from "node:fs";
import { PRODUCT } from "../src/lib/product.ts";

// Pricing is generated from the same source used by the storefront and API.
const source = `/** Generated by npm run sheets:script. Do not edit pricing here. */
const PRODUCT = ${JSON.stringify(PRODUCT, null, 2)};
const SPREADSHEET_ID = "1gjSkd2HqP6M-y4WIqVQGHCPTrIxavKYtKdw937c5y9A";
const ORDER_NUMBER_START = 892;
const HEADERS = ["date", "Full Name", "Adresse", "Telephone", "ville destination", "Prix", "Numero Commande", "Reference produit", "Quantite", "produit", "commentaire", "status", "our comment", "utm source", "utm medium", "utm compaign", "utm content"];

function doPost(e) {
  const lock = LockService.getScriptLock();
  try {
    lock.waitLock(20000);
    const order = JSON.parse(e.postData.contents);
    if (!order || ![1, 2].includes(order.quantity) || !["fr", "ar"].includes(order.language) ||
        typeof order.submissionId !== "string" || !/^[0-9a-f-]{36}$/i.test(order.submissionId) ||
        !["fullName", "phone", "city", "address", "notes"].every(key => typeof order[key] === "string") ||
        !order.fullName.trim() || !order.city.trim() || order.address.trim().length < 8 ||
        !/^(?:0|\\+212)[67]\\d{8}$/.test(order.phone) ||
        order.fullName.length > 120 || order.city.length > 120 || order.address.length > 1000 || order.notes.length > 1000) {
      return reply({ success: false, code: "invalid" });
    }
    const spreadsheet = SpreadsheetApp.openById(SPREADSHEET_ID);
    const sheet = spreadsheet.getSheetByName("Orders");
    if (!sheet) return reply({ success: false, code: "not_configured" });
    if (sheet.getLastRow() === 0) { sheet.appendRow(HEADERS); sheet.setFrozenRows(1); }
    // The website's UUID only identifies a submission retry; customer order numbers are generated here.
    const submissionKey = "submission:" + order.submissionId;
    const properties = PropertiesService.getScriptProperties();
    const existingOrderNumber = properties.getProperty(submissionKey);
    if (existingOrderNumber) return reply({ success: true, orderNumber: existingOrderNumber });
    const orderNumber = nextOrderNumber(sheet);
    order.productSubtotal = order.quantity === 2 ? PRODUCT.bundlePrice : PRODUCT.singlePrice;
    order.shippingCost = PRODUCT.shipping;
    order.orderTotal = order.productSubtotal + order.shippingCost;
    order.timestamp = new Date();
    order.source = "doodly-web";
    // Escape formula prefixes, including +212 telephone numbers, to keep cells as data.
    const safe = value => typeof value === "string" && /^[=+\\-@\\t\\r\\n]/.test(value) ? "'" + value : value;
    const row = [order.timestamp, order.fullName, order.address, order.phone, order.city, order.orderTotal, orderNumber,
      "DOODLY-BLANKET", order.quantity, PRODUCT.name, order.notes, "Nouveau", "", order.utmSource || order.source,
      order.utmMedium || "", order.utmCampaign || "", order.utmContent || ""].map(safe);
    sheet.getRange(sheet.getLastRow() + 1, 1, 1, HEADERS.length).setValues([row]);
    SpreadsheetApp.flush();
    properties.setProperty(submissionKey, orderNumber);
    return reply({ success: true, orderNumber });
  } catch (error) {
    return reply({ success: false, code: "failed" });
  } finally {
    lock.releaseLock();
  }
}

function nextOrderNumber(sheet) {
  const highest = sheet.getLastRow() < 2 ? 0 : sheet.getRange(2, 7, sheet.getLastRow() - 1, 1).getDisplayValues().flat().reduce((max, value) => {
    const match = /^S(\\d+)$/i.exec(String(value).trim());
    return match ? Math.max(max, Number(match[1])) : max;
  }, 0);
  return "S" + Math.max(ORDER_NUMBER_START, highest + 1);
}

function reply(body) {
  return ContentService.createTextOutput(JSON.stringify(body)).setMimeType(ContentService.MimeType.JSON);
}
`;
mkdirSync(new URL("../integrations/", import.meta.url), { recursive: true });
writeFileSync(new URL("../integrations/google-apps-script.gs", import.meta.url), source);
console.log("Generated integrations/google-apps-script.gs from src/lib/product.ts");
